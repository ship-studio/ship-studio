  /** `search::search`: every word must match; newest first; a snippet around the first. */
  function searchAll(query: string): SearchHit[] {
    const words = query.toLowerCase().split(/\s+/).filter(Boolean);
    if (!words.length) return [];
    const hits: SearchHit[] = [];
    for (const a of agents) {
      for (const m of messages.get(a.id) ?? []) {
        const text = m.text.toLowerCase();
        if (!m.text || !words.every((w) => text.includes(w))) continue;
        const at = text.indexOf(words[0]);
        const from = Math.max(0, at - 40);
        const snippet =
          (from ? '…' : '') +
          m.text.slice(from, from + 140).replace(/\s+/g, ' ') +
          (from + 140 < m.text.length ? '…' : '');
        hits.push({
          agentId: a.id,
          agentName: a.name,
          agentColor: a.color,
          messageId: m.id,
          ts: m.ts,
          kind: m.kind,
          ...(m.peer ? { peerName: m.peer.name } : {}),
          snippet,
        });
      }
    }
    return hits.sort((x, y) => y.ts - x.ts).slice(0, 100);
  }

