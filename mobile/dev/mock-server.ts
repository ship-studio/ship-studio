const EXAMPLES =
  'Examples: "in 2 hours", "tomorrow at 9:00", "friday at 14:30", "2026-11-20 09:00", "every weekday at 9:00", "every monday at 8am", "every 2 hours".';
const DAYS = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];

function nextDaily(days: number[], hour: number, minute: number, from: number): number {
  const d = new Date(from);
  d.setSeconds(0, 0);
  d.setHours(hour, minute);
  for (let i = 0; i < 8; i++) {
    if (days.includes(d.getDay()) && d.getTime() > from) return d.getTime();
    d.setDate(d.getDate() + 1);
  }
  return d.getTime();
}

function clock(text: string): [number, number] | null {
  const m = /^(\d{1,2})(?::(\d{2}))?\s*(am|pm)?$/.exec(text.trim());
  if (!m) return null;
  let h = Number(m[1]);
  if (m[3] === 'pm' && h < 12) h += 12;
  if (m[3] === 'am' && h === 12) h = 0;
  return h < 24 ? [h, Number(m[2] ?? 0)] : null;
}

/** A small slice of `schedule::parse`, enough to drive the phone's composer. */
function parseWhen(
  raw: string,
  now: number
): { nextAt: number; repeat?: Repeat } | { error: string } {
  const s = raw.trim().toLowerCase();
  const fail = (why: string) => ({ error: `${why} ${EXAMPLES}` });
  if (!s) return fail('Say when.');
  let m = /^every (\d+ )?(minute|min|hour)s?$/.exec(s);
  if (m) {
    const n = Number(m[1] ?? 1);
    const minutes = m[2] === 'hour' ? n * 60 : n;
    if (minutes < 15) return fail('Routines can repeat every 15 minutes at most.');
    return { nextAt: now + minutes * 60_000, repeat: { kind: 'every', minutes } };
  }
  m = /^every (day|weekday|weekend day|[a-z]+day)s? (?:at )?(.+)$/.exec(s);
  if (m) {
    const t = clock(m[2]);
    if (!t) return fail(`I can't read "${m[2]}" as a time.`);
    const days =
      m[1] === 'day'
        ? [0, 1, 2, 3, 4, 5, 6]
        : m[1] === 'weekday'
          ? [1, 2, 3, 4, 5]
          : m[1] === 'weekend day'
            ? [0, 6]
            : [DAYS.indexOf(m[1])];
    if (days[0] === -1) return fail(`"${m[1]}" isn't a day I know.`);
    return {
      nextAt: nextDaily(days, t[0], t[1], now),
      repeat: { kind: 'days', days, hour: t[0], minute: t[1] },
    };
  }
  m = /^in (\d+) (minute|min|hour|day)s?$/.exec(s);
  if (m) {
    const unit = { minute: 60_000, min: 60_000, hour: 3_600_000, day: 86_400_000 }[m[2]]!;
    return { nextAt: now + Number(m[1]) * unit };
  }
  m = /^(today|tomorrow|[a-z]+day)?\s*(?:at )?(.+)$/.exec(s);
  const t = m ? clock(m[2]) : null;
  if (m && t) {
    const d = new Date(now);
    d.setSeconds(0, 0);
    d.setHours(t[0], t[1]);
    if (m[1] === 'tomorrow') d.setDate(d.getDate() + 1);
    else if (m[1] && m[1] !== 'today') {
      const day = DAYS.indexOf(m[1]);
      if (day === -1) return fail(`I can't read "${m[1]}" as a day.`);
      while (d.getDay() !== day || d.getTime() <= now) d.setDate(d.getDate() + 1);
    } else if (d.getTime() <= now) d.setDate(d.getDate() + 1);
    return { nextAt: d.getTime() };
  }
  return fail(`I can't read "${raw.trim()}" as a time.`);
}
