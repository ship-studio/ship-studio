  function onConnection(ws: WebSocket) {
    let conn: Conn | null = null;
    ws.on('message', (raw) => {
      let frame: ClientFrame;
      try {
        frame = JSON.parse((raw as Buffer).toString()) as ClientFrame;
      } catch {
        return;
      }
      if (!conn) {
        if (frame.t !== 'hello') return ws.close();
        const entry = [...devices.values()].find((d) => d.token === frame.token);
        const refuse = (
          reason: 'unauthorized' | 'revoked' | 'update_app' | 'update_mac',
          message: string
        ) => {
          ws.send(JSON.stringify({ t: 'refused', reason, message } satisfies ServerFrame));
          ws.close();
        };
        if (!entry) return refuse('unauthorized', realRefusal('unauthorized'));
        if (entry.revoked) return refuse('revoked', realRefusal('revoked'));
        const n = negotiate(frame.protocol, SUPPORTED);
        if (!n.ok) {
          return n.update === 'app'
            ? refuse('update_app', realRefusal('update_app'))
            : refuse('update_mac', realRefusal('update_mac'));
        }
        conn = {
          ws,
          deviceId: entry.device.id,
          focus: null,
          foreground: frame.foreground,
          draftSent: new Map(),
        };
        conns.add(conn);
        // The Mac's heartbeat: an unprompted pong every HEARTBEAT_MS.
        const beat = setInterval(() => send(conn!, { t: 'pong' }), HEARTBEAT_MS);
        ws.on('close', () => clearInterval(beat));
        entry.device.connected = true;
        entry.device.lastSeenAt = Date.now();
        const resume = frame.resume;
        const canReplay =
          resume &&
          resume.epoch === epoch &&
          (journal.length === 0 || resume.seq >= journal[0].seq - 1) &&
          resume.seq <= seq;
        send(conn, {
          t: 'welcome',
          protocol: n.version,
          server: { id: serverId, name: MAC_NAME, appVersion: status.appVersion },
          deviceId: entry.device.id,
          resume: canReplay ? 'replay' : 'snapshot',
          // What the real Mac advertises in P1, not what the mock happens to implement.
          methods: realWelcome.methods,
        });
        if (canReplay) {
          for (const e of compact(journal.filter((j) => j.seq > resume.seq))) {
            send(conn, { t: 'evt', seq: e.seq, event: e.event });
          }
        } else {
          ephemeral(
            {
              type: 'sync.snapshot',
              cursor: cursor(),
              overview: overview(),
              status,
              projects: structuredClone(projects),
            },
            conn
          );
        }
        ephemeral({ type: 'sync.caughtUp', cursor: cursor() }, conn);
        // Drafts restart from 0 on a new connection.
        for (const t of turns.values()) if (t.shown) pushDraft(t);
        log(`connected ${entry.device.name} (${canReplay ? 'replay' : 'snapshot'})`);
        return;
      }
      if (frame.t === 'ping') return send(conn, { t: 'pong' });
      if (frame.t === 'presence') {
        conn.foreground = frame.foreground;
        return;
      }
      if (frame.t !== 'req') return;
      const handler = methods[frame.method];
      const c = conn;
      try {
        if (!handler)
          fail({
            type: 'Protocol',
            code: 'unknown_method',
            message: `${frame.method} isn’t available yet`,
          });
        const result = handler!(frame.params as Record<string, unknown>, c);
        send(c, { t: 'res', id: frame.id, ok: true, result } as ServerFrame);
      } catch (error) {
        const e: WireError =
          error instanceof Failure ? error.wire : { type: 'Other', message: String(error) };
        send(c, { t: 'res', id: frame.id, ok: false, error: e });
      }
    });
    ws.on('close', () => {
      if (!conn) return;
      conns.delete(conn);
      const entry = devices.get(conn.deviceId);
      if (entry && ![...conns].some((c) => c.deviceId === conn!.deviceId))
        entry.device.connected = false;
    });
  }

