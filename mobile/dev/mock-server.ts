function seedMessages(a: Agent, now: number): AgentMessage[] {
  const out: AgentMessage[] = [];
  const add = (m: Omit<AgentMessage, 'id' | 'agentId'>) =>
    out.push({ id: `${a.id}_${String(out.length).padStart(4, '0')}`, agentId: a.id, ...m });
  if (a.id === 'chief') {
    // Enough history to page through.
    for (let i = 0; i < 70; i++) {
      const ts = now - (75 - i) * 3_600_000;
      add({ ts, kind: 'user', text: `Morning check-in #${i + 1}: anything blocking?` });
      add({
        ts: ts + 60_000,
        kind: 'agent',
        text: `Nothing blocking. ${i % 3 === 0 ? 'QA 2 finished the nightly run.' : 'Acme Site shipped two small fixes.'}`,
      });
    }
    add({ ts: now - 6 * 60_000, kind: 'user', text: 'Where are we on the launch?' });
    add({ ts: now - 4 * 60_000, kind: 'agent', text: RICH });
  } else if (a.id === 'design') {
    add({ ts: now - 30 * 60_000, kind: 'user', text: 'Export the new icon set to the site.' });
    add({
      ts: now - 28 * 60_000,
      kind: 'agent',
      text: 'Exported 24 icons. I need to copy them into the site repo.',
    });
    add({
      ts: now - 26 * 60_000,
      kind: 'approval',
      text: '',
      approval: {
        requestId: 'req_seed',
        title: 'Write files outside its folder',
        detail: 'cp -r export/icons ~/ShipStudio/acme-site/public/icons',
        status: 'pending',
        tool: 'Bash',
        always: {
          kind: 'command_prefix',
          value: 'cp -r export/icons',
          label: 'cp -r export/icons',
        },
      },
    });
  } else if (a.id === 'fin') {
    add({ ts: now - 3 * 3_600_000, kind: 'user', text: 'Summarise October spend.' });
    add({
      ts: now - 3 * 3_600_000 + 5000,
      kind: 'error',
      text: 'Usage limit reached.',
      failure: { kind: 'usage_limit', resetsAt: now + 2 * 3_600_000 },
    });
  } else {
    add({ ts: a.lastActivityAt - 60_000, kind: 'user', text: 'Status?' });
    add({ ts: a.lastActivityAt, kind: 'agent', text: a.preview ?? 'Done.' });
  }
  return out;
}

