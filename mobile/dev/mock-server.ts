/**
 * A stand-in Mac for building and testing the app without the desktop: the
 * companion protocol (pairing, the WebSocket, the journal with replay and
 * snapshots, drafts, approvals, alerts) over scripted agents.
 *
 * Run it with `pnpm mock` (dev/mock.ts has the options).
 *
 * Every frame follows packages/companion-protocol; the integration test
 * drives the app's own transport against this server.
 */

